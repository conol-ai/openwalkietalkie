#[cfg(test)]
mod tests {
    use crate::ui::{font, font::Font, i18n::Language, layout};

    #[test]
    fn localized_overlay_copy_fits_its_fixed_lanes() {
        let groups: &[(Font, i32, &[&str])] = &[
            (Font::Name, layout::CONFIRM_TEXT.width(), &["Factory reset?", "Keep", "Reset"]),
            (Font::Title, layout::CONFIRM_TEXT.width(), &["Power off?"]),
            (Font::Body, layout::CONFIRM_TEXT.width(), &["Forgets the Bluetooth pairing,", "shows the tutorial, restarts."]),
            (Font::Row, 210, &["hold PTT, say it", "say a label first", "none"]),
            (Font::Row, 180, &["Label", "Modifiers", "Key", "Save", "Remove key"]),
            (Font::Body, layout::TOAST.width() - layout::TOAST_TEXT_X - 12, &[
                "No channel", "Not delivered", "Transcription failed", "Transcription unavailable",
                "Timer done", "Focus complete", "Break complete",
            ]),
            (Font::Small, layout::TOAST.width() - layout::TOAST_TEXT_X - 12, &[
                "pick an agent on the roster first", "Nothing was sent. Try again.",
                "Check the host and try again.", "tap to see the timer", "time for a break; tap to open",
                "tap to return to Pomodoro",
            ]),
            (Font::Keycap, layout::PTT_PILL.width() - 40, &["TRANSCRIBING", "RECORDING", "LISTENING", "NO HOST"]),
        ];
        for language in Language::ALL {
            for &(face, width, keys) in groups {
                for key in keys {
                    let translated = language.text(key);
                    assert!(font::measure(face, translated) <= width, "{} {key}: {translated}", language.code());
                }
            }
        }
    }
}
